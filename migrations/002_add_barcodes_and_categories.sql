create table if not exists public.pos_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

alter table public.backend_test_items
  add column if not exists barcode text unique,
  add column if not exists category_id bigint
    references public.pos_categories(id) on delete set null;

grant select, insert, update, delete on public.pos_categories to anon;
grant usage, select on sequence public.pos_categories_id_seq to anon;

